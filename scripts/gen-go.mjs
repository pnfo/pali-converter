// node scripts/gen-go.mjs [--check] - writes the Go tables from index.js (the source of truth):
//   tables_gen.go  the letter mappings, script info, Tamil maps
//   case_gen.go    the case mappings of String.prototype.toLowerCase/toUpperCase and the Cased/Case_Ignorable
//                  properties (final sigma), so that the Go port lower/upper cases exactly as JS does
// --check fails when a file is out of date (CI).
import fs from 'node:fs'
import { loadConverter } from './load.mjs'

const root = new URL('..', import.meta.url)
const C = loadConverter()

// Go string literal: JSON is valid Go except for invisible characters, written as \u escapes
const str = s => JSON.stringify(s).replace(/[\p{Cf}\p{Cc} ]/gu, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'))
const hex = n => '0x' + n.toString(16).toUpperCase().padStart(4, '0')
const chunked = (items, per, indent = '\t') => items.reduce((lines, x, i) => (i % per ? lines[lines.length - 1].push(x) : lines.push([x]), lines), [])
    .map(l => indent + l.join(', ') + ',').join('\n')
const rows = table => table.map(r => `\t{${r.map(str).join(', ')}},`).join('\n')

const header = `// Code generated by scripts/gen-go.mjs from index.js; DO NOT EDIT.\n\npackage paliconverter\n`

const scriptKeys = Object.keys(C.Script) // SINH...
const tables = `${header}
// Script codes (ISO 15924, lower case), in the order of the JS Script enum.
const (
${scriptKeys.map(k => `\t${k[0] + k.slice(1).toLowerCase()} = ${str(C.Script[k])}`).join('\n')}
)

// scriptCodes are the codes in the order of the JS Script enum.
var scriptCodes = []string{${Object.values(C.Script).map(str).join(', ')}}

// scriptInfo is PaliScriptInfo, in its order (getScriptForCode returns the first script with a range for the code).
var scriptInfo = []ScriptInfo{
${[...C.PaliScriptInfo].map(([code, [name, native, ranges]]) =>
    `\t{Code: ${str(code)}, Name: ${str(name)}, NativeName: ${str(native)}, ranges: [][2]int{${ranges.map(r => `{${hex(r[0])}, ${hex(r[1])}}`).join(', ')}}},`).join('\n')}
}

// scriptIndex is the column of each script in specials, consos and vowels.
var scriptIndex = map[string]int{${Object.entries(C.script_index).map(([k, v]) => `${str(k)}: ${v}`).join(', ')}}

var specials = [][]string{
${rows(C.specials)}
}

var consos = [][]string{
${rows(C.consos)}
}

var vowels = [][]string{
${rows(C.vowels)}
}

var romanDiphthongs = []string{${C.romanDiphthongs.map(str).join(', ')}}

// ivToDv is IV_TO_DV: Sinhala independent vowel to the dependent vowel sign (remove_a).
var ivToDv = map[rune]string{${Object.entries(C.IV_TO_DV).map(([k, v]) => `'${k}': ${str(v)}`).join(', ')}}

// mlTa is ML_TA: Malayalam to Tamil (with superscripts).
var mlTa = map[rune]string{
${chunked(Object.entries(C.ML_TA).map(([k, v]) => `'${k}': ${str(v)}`), 10)}
}

// taMl is TA_ML: Tamil (a letter, with its superscript) to Malayalam.
var taMl = map[string]string{
${chunked(Object.entries(C.TA_ML).map(([k, v]) => `${str(k)}: ${str(v)}`), 10)}
}

// tamilSup are the superscripts of the Tamil letters (TAMIL_SUP).
const tamilSup = ${str(C.TAMIL_SUP)}
`

// case mappings of the JS engine running this script, for every code point
const lowerPairs = [], upperPairs = [], lowerSpecial = [], upperSpecial = []
const cased = [], ignorable = []
const addRange = (ranges, cp) => {
    const last = ranges[ranges.length - 1]
    if (last && last[1] === cp - 1) last[1] = cp
    else ranges.push([cp, cp])
}
for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue
    const ch = String.fromCodePoint(cp)
    for (const [fn, pairs, special] of [['toLowerCase', lowerPairs, lowerSpecial], ['toUpperCase', upperPairs, upperSpecial]]) {
        const m = ch[fn]()
        if (m === ch) continue
        const cps = [...m].map(c => c.codePointAt(0))
        if (cps.length === 1) pairs.push(cp, cps[0])
        else special.push([cp, m])
    }
    if (/\p{Cased}/u.test(ch)) addRange(cased, cp)
    if (/\p{Case_Ignorable}/u.test(ch)) addRange(ignorable, cp)
}
const cases = `${header}
// The case mappings of String.prototype.toLowerCase / toUpperCase (Unicode ${process.versions.unicode}) for every code
// point that changes: pairs of code point, mapping.

var lowerPairs = []rune{
${chunked(lowerPairs.map(hex), 12)}
}

var upperPairs = []rune{
${chunked(upperPairs.map(hex), 12)}
}

// the mappings to more than one code point
var lowerSpecial = map[rune]string{${lowerSpecial.map(([cp, m]) => `${hex(cp)}: ${str(m)}`).join(', ')}}

var upperSpecial = map[rune]string{
${chunked(upperSpecial.map(([cp, m]) => `${hex(cp)}: ${str(m)}`), 6)}
}

// the Cased and Case_Ignorable properties (the final sigma rule of toLowerCase), ranges of code points
var casedRanges = []rune{
${chunked(cased.flat().map(hex), 12)}
}

var caseIgnorableRanges = []rune{
${chunked(ignorable.flat().map(hex), 12)}
}
`

let stale = false
for (const [name, content] of [['tables_gen.go', tables], ['case_gen.go', cases]]) {
    const file = new URL(name, root)
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
            console.error(`${name} is out of date: node scripts/gen-go.mjs`)
            stale = true
        }
    } else {
        fs.writeFileSync(file, content)
        console.log('wrote', name, content.length)
    }
}
if (stale) process.exit(1)
